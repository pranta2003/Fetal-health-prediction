"""scripts/85_eval_ac_nnunet_f0.py

Evaluates AC nnU-Net v2 (Fold 0, 100 epochs) validation predictions on the 142 validation images.
Pipeline:
1. Predict/load the 142 validation masks of Fold 0 (if generated by kernel).
2. Keep the largest connected component and fit an ellipse with cv2.fitEllipseAMS.
3. Calculate AC in mm with per-image pixel size using Ramanujan perimeter formula.
4. Compute metrics on the SAME 142 images for:
   ac-baseline s42, s43, s44, s45, 2-seed average, 4-seed average, and ac-nnunet-f0.
5. Compute paired patient-level cluster bootstrap (5,000 resamples, seed 42) for:
   s43 vs s42, s44 vs s42, s45 vs s42, 4-seed avg vs s42, 4-seed avg vs 2-seed avg,
   and ac-nnunet-f0 comparisons if masks are present.
"""

