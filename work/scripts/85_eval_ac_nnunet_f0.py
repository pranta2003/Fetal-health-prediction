def run_evaluation(
    nnunet_val_dir: Path,
    s42_oof_csv: Path,
    s43_oof_csv: Path,
    s44_oof_csv: Path,
    s45_oof_csv: Path,
    folds_csv: Path,
    data_dir: Path,
    output_json: Path,
) -> dict:
    actual_val_dir = find_validation_directory(nnunet_val_dir)
    print(f"Validation directory checked: {actual_val_dir}")

    s42_oof_csv = Path(s42_oof_csv)
    s43_oof_csv = Path(s43_oof_csv)
    s44_oof_csv = Path(s44_oof_csv)
    s45_oof_csv = Path(s45_oof_csv)
    folds_csv = Path(folds_csv)
    data_dir = Path(data_dir)
    output_json = Path(output_json)

    # 1. Load fold annotations
    folds_df = load_ac_folds(folds_csv=folds_csv, base=data_dir)
    # Fold 1 in folds_v1.csv corresponds to Fold 0 of Dataset502_AC (142 cases, 101 patients)
    val_df = folds_df[folds_df["fold"] == 1].copy().reset_index(drop=True)
    assert len(val_df) == 142, f"Expected 142 validation cases, got {len(val_df)}"

    # 2. Load s42, s43, s44, s45 OOF predictions
    df_s42 = pd.read_csv(s42_oof_csv)
    df_s43 = pd.read_csv(s43_oof_csv)
    df_s44 = pd.read_csv(s44_oof_csv)
    df_s45 = pd.read_csv(s45_oof_csv)

    p_map = dict(zip(folds_df["image_name"], folds_df["patient"]))
    for df in [df_s42, df_s43, df_s44, df_s45]:
        df["patient"] = df["image_name"].map(p_map)

    # Filter all seeds to the exact same 142 cases
    val_images = set(val_df["image_name"])
    sub_s42 = df_s42[df_s42["image_name"].isin(val_images)].sort_values("image_name").reset_index(drop=True)
    sub_s43 = df_s43[df_s43["image_name"].isin(val_images)].sort_values("image_name").reset_index(drop=True)
    sub_s44 = df_s44[df_s44["image_name"].isin(val_images)].sort_values("image_name").reset_index(drop=True)
    sub_s45 = df_s45[df_s45["image_name"].isin(val_images)].sort_values("image_name").reset_index(drop=True)
    val_df = val_df.sort_values("image_name").reset_index(drop=True)

    for name, sub in [("s42", sub_s42), ("s43", sub_s43), ("s44", sub_s44), ("s45", sub_s45)]:
        assert len(sub) == 142, f"Expected 142 rows in {name}, got {len(sub)}"
        assert (sub["image_name"] == val_df["image_name"]).all(), f"Image ordering mismatch in {name}"

    y_true = sub_s42["ac_true"].to_numpy(dtype=float)
    s42_preds = sub_s42["ac_pred"].to_numpy(dtype=float)
    s43_preds = sub_s43["ac_pred"].to_numpy(dtype=float)
    s44_preds = sub_s44["ac_pred"].to_numpy(dtype=float)
    s45_preds = sub_s45["ac_pred"].to_numpy(dtype=float)
    avg_2seed = (s42_preds + s43_preds) / 2.0
    avg_4seed = (s42_preds + s43_preds + s44_preds + s45_preds) / 4.0

    # 3. Check for nnU-Net predicted masks
    has_nnunet_masks = False
    nnunet_preds = []
    if actual_val_dir.exists():
        first_img = val_df.iloc[0]["image_name"]
        first_id = Path(first_img).stem
        cands = [actual_val_dir / f"{first_id}.png", actual_val_dir / f"{first_id}_pred.png"]
        if any(c.is_file() for c in cands):
            has_nnunet_masks = True
            for idx, row in val_df.iterrows():
                img_name = str(row["image_name"])
                case_id = Path(img_name).stem
                mmpp = float(row["px_to_mm_rate"])
                mask_candidates = [
                    actual_val_dir / f"{case_id}.png",
                    actual_val_dir / f"{case_id}_pred.png",
                ]
                mask_file = next((c for c in mask_candidates if c.is_file()), None)
                if mask_file is None:
                    has_nnunet_masks = False
                    break
                mask = cv2.imread(str(mask_file), cv2.IMREAD_GRAYSCALE)
                if mask is None:
                    has_nnunet_masks = False
                    break
                ac_val = fit_ellipse_and_measure_ac(mask, mmpp)
                nnunet_preds.append(ac_val)

    # 4. Compute cohort metrics on the SAME 142 images
    metrics = {
        "ac_baseline_s42": compute_cohort_metrics(y_true, s42_preds),
        "ac_baseline_s43": compute_cohort_metrics(y_true, s43_preds),
        "ac_baseline_s44": compute_cohort_metrics(y_true, s44_preds),
        "ac_baseline_s45": compute_cohort_metrics(y_true, s45_preds),
        "ac_baseline_2seed_avg": compute_cohort_metrics(y_true, avg_2seed),
        "ac_baseline_4seed_avg": compute_cohort_metrics(y_true, avg_4seed),
    }

    if has_nnunet_masks and len(nnunet_preds) == 142:
        nnunet_preds = np.array(nnunet_preds, dtype=float)
        metrics["ac_nnunet_f0"] = compute_cohort_metrics(y_true, nnunet_preds)
    else:
        # Check kernel log to explain execution status
        kernel_log = Path(nnunet_val_dir) / "ac-nnunet-f0.log"
        reason = "Validation masks not generated: nnUNetv2_train command was not found in offline environment"
        if kernel_log.exists():
            log_text = kernel_log.read_text(encoding="utf-8", errors="ignore")
            if "nnUNetv2_train: command not found" in log_text:
                reason = "Execution halted: nnUNetv2_train command not found (offline dependency missing in dataset502-ac)"
        metrics["ac_nnunet_f0"] = {
            "status": "failed_execution",
            "reason": reason,
            "validation_masks_found": False,
        }

    # 5. Paired patient-level cluster bootstrap comparisons (5000 resamples, seed 42)
    # Merged dataframe format: patient, ac_true, ac_pred_a, ac_pred_b -> delta = mae_b - mae_a
    bootstraps = {}

    baseline_comparisons = [
        ("s43_vs_s42", s42_preds, s43_preds),
        ("s44_vs_s42", s42_preds, s44_preds),
        ("s45_vs_s42", s42_preds, s45_preds),
        ("4seed_avg_vs_s42", s42_preds, avg_4seed),
        ("4seed_avg_vs_2seed_avg", avg_2seed, avg_4seed),
    ]

    for comp_name, pred_a, pred_b in baseline_comparisons:
        m_df = pd.DataFrame({
            "patient": val_df["patient"],
            "ac_true": y_true,
            "ac_pred_a": pred_a,
            "ac_pred_b": pred_b,
        })
        boot = patient_level_paired_bootstrap(m_df, n_bootstraps=5000, seed=42)
        bootstraps[comp_name] = boot

    if has_nnunet_masks and len(nnunet_preds) == 142:
        nnunet_comparisons = [
            ("nnunet_vs_s42", s42_preds, nnunet_preds),
            ("nnunet_vs_s43", s43_preds, nnunet_preds),
            ("nnunet_vs_s44", s44_preds, nnunet_preds),
            ("nnunet_vs_s45", s45_preds, nnunet_preds),
            ("nnunet_vs_4seed_avg", avg_4seed, nnunet_preds),
        ]
        for comp_name, pred_a, pred_b in nnunet_comparisons:
            m_df = pd.DataFrame({
                "patient": val_df["patient"],
                "ac_true": y_true,
                "ac_pred_a": pred_a,
                "ac_pred_b": pred_b,
            })
            boot = patient_level_paired_bootstrap(m_df, n_bootstraps=5000, seed=42)
            bootstraps[comp_name] = boot

    results = {
        "cohort": "AC Campaign Fold 0 Validation (Fold 1 of folds_v1.csv)",
        "n_images": 142,
        "n_patients": int(val_df["patient"].nunique()),
        "models": metrics,
        "paired_bootstrap_5000_seed42": bootstraps,
    }

    output_json.parent.mkdir(parents=True, exist_ok=True)
    with open(output_json, "w", encoding="utf-8", newline="\n") as f:
        json.dump(results, f, indent=2)

    print(f"Results successfully saved to {output_json}")
    print("\nSummary on 142 Fold 0 Validation Images:")
    for k, v in metrics.items():
        if isinstance(v, dict) and "mae" in v:
            print(f"  {k:22s} | MAE: {v['mae']:.4f} mm | RMSE: {v['rmse']:.4f} mm | Median: {v['median']:.4f} mm | Bias: {v['bias']:+.4f} mm | NME: {v['nme']:.4f} | >10mm: {v['errors_gt10_rate']*100:.2f}%")
        else:
            print(f"  {k:22s} | {v}")

    print("\nPaired Patient-Level Bootstrap (5000, seed 42):")
    for k, b in bootstraps.items():
        print(f"  {k:25s} | Delta MAE: {b['delta_mae']:+.4f} mm | 95% CI: [{b['ci95_delta_mae'][0]:+.4f}, {b['ci95_delta_mae'][1]:+.4f}] | p = {b['p_val_mae']:.4f}")

    return results


def main():
    args = parse_args()
    print("=" * 70)
    print("AC nnU-Net Fold 0 Evaluation Script")
    print(f"nnU-Net validation dir: {args.nnunet_val_dir}")
    print(f"Target output JSON    : {args.output_json}")
    print("=" * 70)

    run_evaluation(
        nnunet_val_dir=args.nnunet_val_dir,
        s42_oof_csv=args.s42_oof_csv,
        s43_oof_csv=args.s43_oof_csv,
        s44_oof_csv=args.s44_oof_csv,
        s45_oof_csv=args.s45_oof_csv,
        folds_csv=args.folds_csv,
        data_dir=args.data_dir,
        output_json=args.output_json,
    )


if __name__ == "__main__":
    main()
