"""make_hadlock_step2_notebook.py: Generate and format notebooks/benchmarks/hadlock_step2.ipynb."""

from pathlib import Path
import nbformat as nbf

REPO_ROOT = Path(__file__).resolve().parent.parent

def create_hadlock_step2_notebook():
    nb = nbf.v4.new_notebook()

    nb.cells = [
        nbf.v4.new_markdown_cell(
            "# Hadlock Demo Step 2: Multi-Plane EFW Estimation Benchmark\n\n"
            "This notebook evaluates multi-plane Estimated Fetal Weight (EFW) using Hadlock's 4-parameter formula "
            "($EFW = f(BPD, HC, AC, FL)$) on the strictly held-out three-plane test cohort ($N = 22$ subjects: 17 FP + 5 UCL).\n\n"
            "### Protocol & Integrity Rules\n"
            "- **Zero Cross-Plane Leakage**: Strictly evaluated on subjects whose images are in the official Test split across "
            "Head, Abdomen, and Femur planes simultaneously (FP: 17, UCL: 5, Total: 22 subjects).\n"
            "- **Zero Hand-Typed Numbers**: All metrics and tables are generated by `scripts/26_hadlock_demo_step2.py` "
            "reading committed prediction files.\n"
            "- **No Post-Delivery or GA Leakage**: Strictly biometry-based; no birth weight, no gestational age, and no percentiles exist or are used.\n"
            "- **Formula Consistency**: HC is computed using the Ramanujan second approximation formula from OFD/BPD identically "
            "for both annotated and predicted head calipers."
        ),
        nbf.v4.new_code_cell(
            "import json\n"
            "from pathlib import Path\n"
            "import sys\n"
            "import pandas as pd\n"
            "from IPython.display import display, Markdown\n\n"
            "# Locate repository root\n"
            "work_dir = Path.cwd().resolve()\n"
            "while work_dir.name != 'work' and work_dir.parent != work_dir:\n"
            "    work_dir = work_dir.parent\n\n"
            "sys.path.insert(0, str(work_dir / 'src'))\n\n"
            "results_dir = work_dir / 'docs' / 'results' / 'hadlock_demo'\n"
            "summary_md_path = results_dir / 'step2_summary.md'\n"
            "summary_json_path = results_dir / 'step2_summary.json'\n"
            "per_subject_csv_path = results_dir / 'step2_per_subject.csv'\n\n"
            "assert summary_md_path.is_file(), f'Missing {summary_md_path}'\n"
            "assert summary_json_path.is_file(), f'Missing {summary_json_path}'\n"
            "assert per_subject_csv_path.is_file(), f'Missing {per_subject_csv_path}'\n\n"
            "with open(summary_json_path, 'r', encoding='utf-8') as f:\n"
            "    summary_data = json.load(f)\n\n"
            "print('Loaded Hadlock Step 2 Summary JSON.')\n"
            "print('Test Vector Check:', summary_data['metadata']['test_vector_check'])\n"
            "print('Cohort Size:', summary_data['metadata']['n_total_cohort'], 'subjects')\n\n"
            "display(Markdown(summary_md_path.read_text(encoding='utf-8')))"
        ),
        nbf.v4.new_code_cell(
            "# Per-Subject Results Table\n"
            "df_subj = pd.read_csv(per_subject_csv_path)\n"
            "display_cols = [\n"
            "    'subject_id', 'source', 'n_head_images', 'n_abdomen_images', 'n_femur_images',\n"
            "    'bpd_annotated_mm', 'bpd_predicted_mm', 'hc_annotated_mm', 'hc_predicted_mm',\n"
            "    'ac_annotated_mm', 'ac_predicted_mm', 'fl_annotated_mm', 'fl_predicted_mm',\n"
            "    'efw_annotated_g', 'efw_predicted_g', 'err_g', 'err_pct'\n"
            "]\n"
            "print(f'Total cohort subjects: {len(df_subj)} ({dict(df_subj[\"source\"].value_counts())})')\n"
            "display(df_subj[display_cols])"
        ),
        nbf.v4.new_code_cell(
            "# One-at-a-Time Replacement Analysis Table\n"
            "rep_data = summary_data['replacement_analysis']\n"
            "rep_rows = [\n"
            "    {'Condition': 'Replace BPD only', 'Mean Abs Error (%)': rep_data['replace_bpd_only_mean_abs_pct']},\n"
            "    {'Condition': 'Replace HC only', 'Mean Abs Error (%)': rep_data['replace_hc_only_mean_abs_pct']},\n"
            "    {'Condition': 'Replace AC only', 'Mean Abs Error (%)': rep_data['replace_ac_only_mean_abs_pct']},\n"
            "    {'Condition': 'Replace FL only', 'Mean Abs Error (%)': rep_data['replace_fl_only_mean_abs_pct']},\n"
            "    {'Condition': 'Replace All Four (Full Model)', 'Mean Abs Error (%)': rep_data['replace_all_four_mean_abs_pct']},\n"
            "]\n"
            "df_rep = pd.DataFrame(rep_rows)\n"
            "df_rep['Relative Error Share (%)'] = round(df_rep['Mean Abs Error (%)'] / rep_data['replace_all_four_mean_abs_pct'] * 100.0, 1)\n"
            "print('Replacement Analysis:')\n"
            "print(rep_data['statement'])\n"
            "display(df_rep)"
        ),
        nbf.v4.new_code_cell(
            "# Predicted vs Annotated EFW Scatter Plot\n"
            "import matplotlib.pyplot as plt\n\n"
            "fig, ax = plt.subplots(figsize=(8, 7), dpi=120)\n\n"
            "fp_mask = df_subj['source'] == 'FP'\n"
            "ucl_mask = df_subj['source'] == 'UCL'\n\n"
            "ax.scatter(\n"
            "    df_subj.loc[fp_mask, 'efw_annotated_g'],\n"
            "    df_subj.loc[fp_mask, 'efw_predicted_g'],\n"
            "    c='#1f77b4', marker='o', s=65, alpha=0.85, label=f'FP (n={fp_mask.sum()})'\n"
            ")\n"
            "ax.scatter(\n"
            "    df_subj.loc[ucl_mask, 'efw_annotated_g'],\n"
            "    df_subj.loc[ucl_mask, 'efw_predicted_g'],\n"
            "    c='#ff7f0e', marker='s', s=75, alpha=0.9, label=f'UCL (n={ucl_mask.sum()})'\n"
            ")\n\n"
            "# Identity line\n"
            "min_val = min(df_subj['efw_annotated_g'].min(), df_subj['efw_predicted_g'].min()) * 0.95\n"
            "max_val = max(df_subj['efw_annotated_g'].max(), df_subj['efw_predicted_g'].max()) * 1.05\n"
            "ax.plot([min_val, max_val], [min_val, max_val], 'r--', lw=1.5, label='Identity Line (y = x)')\n\n"
            "# Outlier UCL_5 label\n"
            "ucl5 = df_subj[df_subj['subject_id'] == 'UCL_5'].iloc[0]\n"
            "ax.annotate(\n"
            "    f\"UCL_5\\n({ucl5['err_g']:+.1f}g, {ucl5['err_pct']:+.1f}%)\",\n"
            "    (ucl5['efw_annotated_g'], ucl5['efw_predicted_g']),\n"
            "    textcoords='offset points', xytext=(-40, 15),\n"
            "    arrowprops=dict(arrowstyle='->', color='black', lw=0.8),\n"
            "    fontsize=9\n"
            ")\n\n"
            "mae_val = summary_data['primary_evaluation_r4']['all_cohort_22']['mae_g']\n"
            "mape_val = summary_data['primary_evaluation_r4']['all_cohort_22']['mape_pct']\n"
            "bias_val = summary_data['primary_evaluation_r4']['all_cohort_22']['bias_pct']\n\n"
            "ax.set_xlabel('Annotated EFW (grams)', fontsize=11)\n"
            "ax.set_ylabel('Predicted EFW (grams)', fontsize=11)\n"
            "ax.set_title(f'Hadlock 4-Parameter EFW: Predicted vs Annotated (N={len(df_subj)})\\nMAE = {mae_val:.2f} g, MAPE = {mape_val:.2f}%, Bias = {bias_val:+.2f}%', fontsize=12)\n"
            "ax.grid(True, linestyle=':', alpha=0.6)\n"
            "ax.legend(loc='upper left', frameon=True)\n"
            "plt.tight_layout()\n"
            "plt.show()"
        ),
        nbf.v4.new_code_cell(
            "# Integrity & Verification Assertions\n"
            "import sys\n"
            "sys.path.insert(0, str(work_dir / 'src'))\n"
            "from fetal.explain.hadlock import calculate_efw\n\n"
            "# 1. Test vector assertion\n"
            "efw_test = calculate_efw(280.0, 80.0, 250.0, 55.0)\n"
            "assert abs(efw_test - 1403.0) < 0.1, f'Expected 1403.0g, got {efw_test}'\n\n"
            "# 2. Cohort assertions\n"
            "assert len(df_subj) == 22, f'Expected 22 subjects, got {len(df_subj)}'\n"
            "assert (df_subj['source'] == 'FP').sum() == 17\n"
            "assert (df_subj['source'] == 'UCL').sum() == 5\n\n"
            "# 3. Recomputed math on every subject\n"
            "for _, row in df_subj.iterrows():\n"
            "    recomputed_ann = calculate_efw(row['hc_annotated_mm'], row['bpd_annotated_mm'], row['ac_annotated_mm'], row['fl_annotated_mm'])\n"
            "    recomputed_pred = calculate_efw(row['hc_predicted_mm'], row['bpd_predicted_mm'], row['ac_predicted_mm'], row['fl_predicted_mm'])\n"
            "    assert abs(recomputed_ann - row['efw_annotated_g']) < 0.15\n"
            "    assert abs(recomputed_pred - row['efw_predicted_g']) < 0.15\n"
            "    assert abs((recomputed_pred - recomputed_ann) - row['err_g']) < 0.2\n\n"
            "# 4. Replacement analysis ranking\n"
            "assert rep_data['dominant_driver'] == 'AC'\n"
            "assert rep_data['replace_ac_only_mean_abs_pct'] > rep_data['replace_fl_only_mean_abs_pct']\n"
            "assert rep_data['replace_fl_only_mean_abs_pct'] > rep_data['replace_hc_only_mean_abs_pct']\n"
            "assert rep_data['replace_hc_only_mean_abs_pct'] > rep_data['replace_bpd_only_mean_abs_pct']\n\n"
            "print('All Hadlock step 2 integrity assertions passed successfully.')"
        ),
    ]

    out_file = REPO_ROOT / "notebooks" / "benchmarks" / "hadlock_step2.ipynb"
    out_file.parent.mkdir(parents=True, exist_ok=True)
    with open(out_file, "w", encoding="utf-8") as f:
        nbf.write(nb, f)
    print(f"Created {out_file}")

if __name__ == "__main__":
    create_hadlock_step2_notebook()
